// Implements TEST_PLAN.md Section G: React Syntax Highlighter Integration Validation
import { generateDateHash } from '../support/utils';

describe('React Syntax Highlighter Integration Validation (Section G)', () => {
  it('creates Lesson 2000 with a Python code block and verifies syntax highlighting (Test Case 11)', () => {
    cy.signedInSession('editor');
    cy.deleteLessonIfExists('/cs/scratch1A', '2000');

    // Capture after the cleanup helper so only this test's own prompts are counted.
    cy.captureConfirms().as('confirms');

    cy.visit('/cs/scratch1A');

    const lessonTitle = generateDateHash('Syntax and Blocks Integration Test');
    const contentHash = generateDateHash('import-random-hash');
    const pythonCode = `
# Content Hash: ${contentHash}
import random

def battle_ready(pokemon):
    hp = random.randint(50, 100)
    print(pokemon + " is ready with " + str(hp) + " HP!")
`;

    // 1. Add New Lesson
    cy.contains('button', 'Add New Lesson').click();
    cy.get('[data-testid="editor-modal"]').should('be.visible');

    cy.get('[data-testid="editor-modal"]').find('input[type="number"]').type('2000');
    cy.get('[data-testid="editor-modal"]')
      .find('input[placeholder="Lesson title"]')
      .type(lessonTitle);
    cy.get('#content-textarea').type('This is an integration test for syntax highlighting.\n\n');

    // Use formatting helper to insert python code block
    cy.get('button[title="Insert Code Block"]').click();
    cy.get('[data-testid="code-block-modal"]').should('be.visible');
    cy.get('[data-testid="code-block-modal"]').find('select').select('python');
    cy.get('[data-testid="code-block-modal"]').find('textarea').clear();
    cy.get('[data-testid="code-block-modal"]').find('textarea').type(pythonCode);
    cy.get('[data-testid="code-block-modal"]').contains('button', 'Insert Code Block').click();

    cy.get('[data-testid="editor-modal"]').contains('button', 'Save').click();

    // 2. Click the Lesson 2000 link from the list
    cy.contains('[data-testid="lesson-link"]', `Lesson 2000: ${lessonTitle}`)
      .should('be.visible')
      .click();
    cy.url().should('include', '/cs/scratch1A/lesson/2000');

    // 3. Assertions on Syntax Highlighter rendering
    // Verify the code block is rendered inside a pre element with syntax highlighting spans
    cy.get('[data-testid="lesson-content"]').find('pre code').should('be.visible');
    cy.get('[data-testid="lesson-content"]')
      .find('pre code')
      .should('contain', `Content Hash: ${contentHash}`);
    cy.get('[data-testid="lesson-content"]').find('pre code').should('contain', 'import random');
    cy.get('[data-testid="lesson-content"]').find('pre code').should('contain', 'def battle_ready');
    cy.get('[data-testid="lesson-content"]').find('pre code').should('contain', 'print');

    // Verify token spans are generated by react-syntax-highlighter
    cy.get('[data-testid="lesson-content"]')
      .find('pre code span')
      .should('have.length.at.least', 5);

    // Cleanup: Delete Lesson 2000
    cy.contains('button', 'Edit Lesson').click();
    cy.get('[data-testid="editor-modal"]').should('be.visible');

    cy.get('[data-testid="editor-modal"]').contains('button', 'Delete').click();

    // Deleting is the only thing in this test that should have prompted.
    cy.get('@confirms').should('have.length', 1);
    cy.get('@confirms').its(0).should('contain', 'delete this lesson');

    // Verify redirection and removal
    cy.url().should('eq', Cypress.config().baseUrl + '/cs/scratch1A');
    cy.contains('[data-testid="lesson-link"]', `Lesson 2000: ${lessonTitle}`).should('not.exist');
  });
});
